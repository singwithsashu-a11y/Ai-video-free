"""Local-first AI helpers: Ollama (no API key) and deterministic offline templates."""
import os
import httpx
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field

router = APIRouter(prefix="/api", tags=["local-ai"])


class LocalAIRequest(BaseModel):
    prompt: str = Field(min_length=1, max_length=12000)
    mode: str = "script"
    provider: str = "local"


SYSTEM_PROMPTS = {
    "script": "You are a professional short-form video writer. Reply in the user's language. Create a strong hook, scene-by-scene visuals, narration, on-screen captions, and a closing CTA. Be specific, avoid filler.",
    "storyboard": "You are a film storyboard artist. Reply in the user's language. Make a numbered scene table with duration, camera framing, action, visual prompt, narration, and transition. Keep character and location continuity.",
    "caption": "You are a social media copywriter. Reply in the user's language. Provide five distinct captions, a concise hook, and relevant hashtags.",
}


def offline_generate(prompt: str, mode: str) -> str:
    """Transparent no-model fallback. This is template logic, not an LLM."""
    idea = prompt.strip()
    if mode == "caption":
        return (
            f"HOOK: {idea[:140]}\n\n"
            f"CAPTION 1: Ye kahani aapko sochne par majboor karegi — end tak dekho.\n"
            f"CAPTION 2: Ek chhota sa idea, ek badi baat. Aapki kya rai hai?\n"
            f"CAPTION 3: Is moment ko miss mat karna.\n"
            f"CAPTION 4: Sach, emotion aur ek powerful message.\n"
            f"CAPTION 5: Apne dost ke saath share karo.\n\n"
            "#Shorts #Reels #Hindi #Hinglish #Video"
        )
    if mode == "storyboard":
        return (
            f"OFFLINE STORYBOARD TEMPLATE\nIDEA: {idea}\n\n"
            "SCENE 1 (0–3s) — HOOK: Show the most surprising image; large on-screen hook.\n"
            "SCENE 2 (3–8s) — CONTEXT: Establish the place/person/problem with a wide shot.\n"
            "SCENE 3 (8–15s) — DEVELOPMENT: Show two close-up details that explain the idea.\n"
            "SCENE 4 (15–23s) — PAYOFF: Reveal the key moment or emotional turn.\n"
            "SCENE 5 (23–30s) — END: Resolve the idea and add a simple call to action.\n\n"
            "For every scene, keep the same character, wardrobe, location, and lighting unless the story calls for a change. "
            "This is a reusable template; a local language model will make it idea-specific."
        )
    return (
        f"OFFLINE SCRIPT TEMPLATE\nIDEA: {idea}\n\n"
        "HOOK (0–3s): Start with a surprising question or bold claim related to the idea.\n"
        "SCENE 1 (3–8s): Establish the situation with one clear visual.\n"
        "NARRATION: Explain why this topic matters in one short sentence.\n"
        "SCENE 2 (8–18s): Show the main conflict, fact, or emotional moment.\n"
        "NARRATION: Add one concrete detail; keep sentences short and natural.\n"
        "SCENE 3 (18–27s): Deliver the reveal, lesson, or emotional payoff.\n"
        "ENDING (27–30s): Finish with a memorable line and a simple question for viewers.\n\n"
        "This is an offline template, not generated by a language model. Select Local Ollama for custom AI writing."
    )


@router.get("/local-ai/status")
async def local_ai_status():
    base = os.getenv("OLLAMA_BASE_URL", "http://127.0.0.1:11434").strip().rstrip("/")
    try:
        async with httpx.AsyncClient(timeout=3) as client:
            response = await client.get(f"{base}/api/tags")
        response.raise_for_status()
        models = [m.get("name", "") for m in response.json().get("models", [])]
        return {"available": True, "base_url": base, "models": models,
                "default_model": os.getenv("OLLAMA_MODEL", "qwen2.5:3b")}
    except (httpx.HTTPError, ValueError):
        return {"available": False, "base_url": base, "models": [],
                "default_model": os.getenv("OLLAMA_MODEL", "qwen2.5:3b"),
                "message": "Ollama is not reachable from this server."}


@router.post("/local-ai")
async def local_ai(req: LocalAIRequest):
    provider = req.provider.lower().strip()
    if provider == "offline":
        return {"text": offline_generate(req.prompt, req.mode), "provider": "offline-template"}
    if provider != "local":
        raise HTTPException(400, "provider must be 'local' or 'offline'.")

    base = os.getenv("OLLAMA_BASE_URL", "http://127.0.0.1:11434").strip().rstrip("/")
    model = os.getenv("OLLAMA_MODEL", "qwen2.5:3b").strip()
    if not model:
        raise HTTPException(500, "OLLAMA_MODEL is empty. Set it to an installed Ollama model.")
    system = SYSTEM_PROMPTS.get(req.mode, SYSTEM_PROMPTS["script"])
    try:
        async with httpx.AsyncClient(timeout=180) as client:
            response = await client.post(
                f"{base}/api/chat",
                json={"model": model, "stream": False,
                      "messages": [{"role": "system", "content": system},
                                   {"role": "user", "content": req.prompt}]},
            )
        if response.status_code >= 400:
            raise HTTPException(502, f"Ollama returned HTTP {response.status_code}: {response.text[:500]}")
        data = response.json()
        answer = data.get("message", {}).get("content", "").strip()
        if not answer:
            raise HTTPException(502, "Ollama returned an empty response. Check that the selected model is installed.")
        return {"text": answer, "provider": "ollama", "model": model}
    except httpx.RequestError:
        raise HTTPException(
            503,
            "Local Ollama is not reachable from the machine running this backend. Install Ollama there, run it, "
            "and pull a model (example: ollama pull qwen2.5:3b), or choose Offline Template. "
            "On shared hosting, 127.0.0.1 means the hosting server, not your phone or PC.",
        )
